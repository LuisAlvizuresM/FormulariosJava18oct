    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
double km = Double.parseDouble(txtKilometraje.getText());

if (indice < 7) {
    rutas[indice] = km;
    indice++;
    JOptionPane.showMessageDialog(this, "Ruta agregada correctamente (" + indice + "/7)");
    txtKilometraje.setText(""); 
} else {
    JOptionPane.showMessageDialog(this, "Ya ingresó las 7 rutas de la semana.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
if (indice < 7) {
    JOptionPane.showMessageDialog(this, "Aún no ha ingresado las 7 rutas.");
    return;
}

double total = 0;

for (int i = 0; i < 7; i++) {
    total = total + rutas[i];
}

double promedio = total / 7;


try {
    File carpeta = new File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs(); // Crea la carpeta si no existe
    }
    
    try (FileWriter escritor = new FileWriter("temp/sunombre_reporte_rutas.txt")) {
        escritor.write("Reporte Semanal de Rutas\n");
        escritor.write("Total de Kilómetros: " + total + "\n");
        escritor.write("Promedio Diario: " + promedio + "\n");
        
    }
    
    JOptionPane.showMessageDialog(this, "Reporte guardado con éxito en la carpeta temp.");
} catch (HeadlessException | IOException e) {
    JOptionPane.showMessageDialog(this, "Error al guardar el archivo: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnReporteActionPerformed

