    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
if (indice < 5) {
    JOptionPane.showMessageDialog(this, "Debe ingresar las 5 tareas primero.");
    return;
}

try {
    File carpeta = new File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }
    
    try (FileWriter escritor = new FileWriter("temp/sunombre_agenda.txt")) {
        escritor.write("Agenda de Tareas\n");
        for (int i = 0; i < 5; i++) {
            escritor.write((i + 1) + ". " + tareas[i] + "\n");
        }
    }
    
    JOptionPane.showMessageDialog(this, "Agenda exportada correctamente.");
} catch (HeadlessException | IOException e) {
    JOptionPane.showMessageDialog(this, "Error al exportar: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnExportarActionPerformed

