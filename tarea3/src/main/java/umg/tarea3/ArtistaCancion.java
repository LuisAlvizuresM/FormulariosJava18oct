    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
                                              
    
    String nom = txtNombreArtista.getText();
    String pais = txtPais.getText();
    int oyentes = Integer.parseInt(txtOyentes.getText());

   
    Artista art = new Artista();

   
    art.nombre = nom;
    art.paisOrigen = pais;
    art.oyentesMensuales = oyentes;

    
    txtAreaResultados.append("--- ARTISTA CREADO ---\n");
    txtAreaResultados.append("Nombre: " + art.nombre + "\n");
    txtAreaResultados.append("País: " + art.paisOrigen + "\n");
    txtAreaResultados.append("Oyentes: " + art.oyentesMensuales + "\n\n");
    
   
    txtNombreArtista.setText("");
    txtPais.setText("");
    txtOyentes.setText("");        // TODO add your handling code here:
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
                                             
    String tit = txtTitulo.getText();
    String artNombre = txtArtistaCancion.getText();
    int dur = Integer.parseInt(txtDuracion.getText());
    String gen = txtGenero.getText();

    
    Cancion can = new Cancion();

    
    can.titulo = tit;
    can.nombreArtista = artNombre;
    can.duracionSegundos = dur;
    can.genero = gen;

   
    txtAreaResultados.append("--- CANCIÓN CREADA ---\n");
    txtAreaResultados.append("Título: " + can.titulo + "\n");
    txtAreaResultados.append("Intérprete: " + can.nombreArtista + "\n");
    txtAreaResultados.append("Duración: " + can.duracionSegundos + " seg\n");
    txtAreaResultados.append("Género: " + can.genero + "\n\n");

   
    txtTitulo.setText("");
    txtArtistaCancion.setText("");
    txtDuracion.setText("");
    txtGenero.setText("");
      
    }//GEN-LAST:event_btnCrearCancionActionPerformed

