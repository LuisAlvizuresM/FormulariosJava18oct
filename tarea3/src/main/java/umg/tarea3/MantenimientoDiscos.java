    public void cargarDatosAuto() {
    try {
        File archivo = new File("temp/discos.csv");
        if (!archivo.exists()) {
            JOptionPane.showMessageDialog(this, "El archivo temp/discos.csv no existe.");
            return;
        }

        Scanner sc = new Scanner(archivo);
        int i = 0;
        while (sc.hasNextLine() && i < 5) {
            String linea = sc.nextLine().trim(); 
            if (!linea.isEmpty()) {
                String[] partes = linea.split(",");
                titulos[i] = partes[0].trim();  
                anios[i] = Integer.parseInt(partes[1].trim()); 
                i++;
            }
        }
        sc.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar datos: " + e.getMessage());
    }
}
