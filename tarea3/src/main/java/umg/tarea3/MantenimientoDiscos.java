    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
String busqueda = txtBuscar.getText();
boolean encontrado = false;

for (int i = 0; i < 5; i++) {
    if (titulos[i] != null && titulos[i].equalsIgnoreCase(busqueda)) {
        lblAnioActual.setText("Año Actual: " + anios[i]);
        encontrado = true;
        break;
    }
}

if (!encontrado) {
    JOptionPane.showMessageDialog(this, "Disco no encontrado.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
String busqueda = txtBuscar.getText();
    int nuevoAnio = Integer.parseInt(txtNuevoAnio.getText());
    boolean encontrado = false;

    for (int i = 0; i < 5; i++) {
        if (titulos[i] != null && titulos[i].equalsIgnoreCase(busqueda)) {
            anios[i] = nuevoAnio; 
            lblAnioActual.setText("Año Actual: " + nuevoAnio); 
            encontrado = true;
            break;
        }
    }

    if (!encontrado) {
        JOptionPane.showMessageDialog(this, "Disco no encontrado para actualizar.");
        return;
    }

   
    try {
        FileWriter escritor = new FileWriter("temp/discos.csv", false); // false para sobrescribir
        for (int i = 0; i < 5; i++) {
            if (titulos[i] != null) {
                escritor.write(titulos[i] + "," + anios[i] + "\n");
            }
        }
        escritor.close();
        JOptionPane.showMessageDialog(this, "Registro actualizado y guardado en archivo.");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    

}        // TODO add your handling code here:
    }//GEN-LAST:event_btnActualizarActionPerformed

